"""Стоп-фразы: «стоп», «отмена», «хватит» — остановить самого ассистента.

Такая фраза — одна или с именем («Джарвис, стоп») — не команда: она прерывает задачу
нейросети, речь ассистента и прослушивание, где бы её ни сказали или ни ввели текстом.
"""

from __future__ import annotations

# Слова, которыми останавливают ассистента (и голосом, и текстом).
STOP_PHRASES = ("стоп", "отмена", "отмени", "хватит", "прекрати")
_STOP_WORDS = frozenset(STOP_PHRASES)


def is_stop_phrase(normalized: str) -> bool:
    """Во фразе (уже без имени и слов-паразитов) одни стоп-слова: «стоп», «хватит, отмена».

    «Отмени таймер» — не стоп-фраза, а команда.
    """
    words = normalized.split()
    return bool(words) and all(word in _STOP_WORDS for word in words)
